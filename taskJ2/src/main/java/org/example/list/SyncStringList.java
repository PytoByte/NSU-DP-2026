package org.example.list;

/**
 * Задаёт контракт потокобезопасного списка строк, с которым одинаково работают и
 * ввод, и несколько сортирующих нитей.
 *
 * <p>Намеренно {@link Iterable}: вывод состояния списка выполняется обычным
 * циклом for-each. {@link #iterator()} обязан возвращать согласованный снимок,
 * чтобы печать в любой момент содержала ровно ранее введённые строки.
 */
public interface SyncStringList extends Iterable<String> {

    /**
     * Атомарно вставляет значение в начало списка.
     *
     * @param value вставляемое значение
     */
    void addFirst(String value);

    /**
     * Возвращает текущее количество записей.
     *
     * @return число записей в списке
     */
    int size();
}
